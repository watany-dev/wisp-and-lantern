// Aggregates the evidence into docs/evidence/metrics.md, the only source for numbers in the write-up.
// - docs/evidence/kiro-log/*.jsonl: records per surface x kind, and sessions
// - docs/evidence/timelog.md: minutes per surface
// - merged pull requests, if the `gh` CLI is available and signed in
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LOG_DIR = "docs/evidence/kiro-log";
const TIMELOG = "docs/evidence/timelog.md";
const OUT = "docs/evidence/metrics.md";

// Kiro log
const counts = new Map(); // surface -> Map(kind -> n)
const sessions = new Set();
let records = 0;
let malformed = 0;
const logFiles = existsSync(LOG_DIR) ? readdirSync(LOG_DIR).filter((f) => f.endsWith(".jsonl")) : [];
for (const file of logFiles) {
  for (const line of readFileSync(join(LOG_DIR, file), "utf8").split("\n")) {
    if (!line.trim()) continue;
    let rec;
    try {
      rec = JSON.parse(line);
    } catch {
      malformed += 1;
      continue;
    }
    records += 1;
    sessions.add(rec.session ?? file);
    const surface = rec.surface || "unknown";
    const kind = rec.kind || "unknown";
    if (!counts.has(surface)) counts.set(surface, new Map());
    counts.get(surface).set(kind, (counts.get(surface).get(kind) ?? 0) + 1);
  }
}
const kinds = [...new Set([...counts.values()].flatMap((m) => [...m.keys()]))].sort();
const surfaces = [...counts.keys()].sort();

// Time log: | date | surface | spec/task | start | end | minutes | PR | note |
const minutesBySurface = new Map();
const toMinutes = (hhmm) => {
  const m = /^(\d{1,2}):(\d{2})$/.exec(hhmm);
  return m ? Number(m[1]) * 60 + Number(m[2]) : null;
};
if (existsSync(TIMELOG)) {
  for (const line of readFileSync(TIMELOG, "utf8").split("\n")) {
    const cells = line.split("|").slice(1, -1).map((c) => c.trim());
    if (cells.length < 6 || cells[0] === "date" || /^-+$/.test(cells[0].replace(/:/g, ""))) continue;
    const [, surface, , start, end, minutesCell] = cells;
    let minutes = Number(minutesCell);
    if (!minutesCell || Number.isNaN(minutes)) {
      const s = toMinutes(start);
      const e = toMinutes(end);
      minutes = s !== null && e !== null && e >= s ? e - s : NaN;
    }
    if (Number.isNaN(minutes) || !surface) continue;
    minutesBySurface.set(surface, (minutesBySurface.get(surface) ?? 0) + minutes);
  }
}
const totalMinutes = [...minutesBySurface.values()].reduce((a, b) => a + b, 0);

// Merged pull requests
let mergedPrs = "n/a (gh unavailable)";
try {
  const out = execFileSync("gh", ["pr", "list", "--state", "merged", "--limit", "1000", "--json", "number"], {
    stdio: ["ignore", "pipe", "ignore"],
  });
  mergedPrs = String(JSON.parse(out.toString()).length);
} catch {
  // keep n/a
}

const lines = [
  "# Metrics",
  "",
  `Generated by \`npm run metrics\` at ${new Date().toISOString()}. Numbers in the write-up come only from this file.`,
  "",
  "## Kiro hook records",
  "",
  `- Sessions: ${sessions.size}`,
  `- Records: ${records}${malformed ? ` (${malformed} malformed lines skipped)` : ""}`,
  "",
];
if (surfaces.length) {
  lines.push(`| surface | ${kinds.join(" | ")} | total |`, `|---|${kinds.map(() => "---|").join("")}---|`);
  for (const s of surfaces) {
    const m = counts.get(s);
    const row = kinds.map((k) => m.get(k) ?? 0);
    lines.push(`| ${s} | ${row.join(" | ")} | ${row.reduce((a, b) => a + b, 0)} |`);
  }
} else {
  lines.push("No records yet.");
}
lines.push("", "## Time per surface (from timelog.md)", "");
if (minutesBySurface.size) {
  lines.push("| surface | minutes | hours |", "|---|---|---|");
  for (const [s, m] of [...minutesBySurface].sort()) lines.push(`| ${s} | ${m} | ${(m / 60).toFixed(1)} |`);
  lines.push(`| **total** | **${totalMinutes}** | **${(totalMinutes / 60).toFixed(1)}** |`);
} else {
  lines.push("No entries yet.");
}
lines.push("", "## Pull requests", "", `- Merged: ${mergedPrs}`, "");

writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT}`);
